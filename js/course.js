/* Все фразы, которые Штрих может произнести (для нейро-озвучки tools/make_voice.py) */
function allSpeech(tr){
  const o=new Set(),add=s=>o.add(s);
  const T=(s,...a)=>{let r=tr(s);a.forEach((v,i)=>r=r.split('{'+i+'}').join(v));return r;};
  add(T('Привет! Я Штрих. Нажми на котика, будем рисовать!'));
  add(T('Ты прошёл все уровни! Ты настоящий художник. Нарисуй другие рисунки в любой технике.'));
  add(T('Привет! Я Штрих. Давай рисовать!'));
  add(T('Возьми листок и карандаш.'));
  add(T('Наклейка твоя! Она уже в альбоме.'));add(T('Ещё одна наклейка! Отлично получилось!'));add(T('Открыт следующий урок.'));
  add(T('Вот твои наклейки!'));add(T('Тут будут твои наклейки. Нарисуй первого котика!'));
  for(let n=1;n<=6;n++)add(T('Осталось: {0}.',n));
  PRAISE.forEach(p=>add(T(p)));
  LEVELS.forEach((lv,i)=>{add(T(lv.intro));add(T('Уровень {0} откроется, когда ты пройдёшь уровень {1}.',i+1,i));add(T('Ура! Открыт новый уровень: {0}!',T(lv.name)));});
  TECHS.forEach(t=>{add(T('Сегодня учимся: «{0}». Нажми и выбери рисунок!',T(t.tech)));add(T('Сначала нарисуй любой рисунок в технике «{0}»!',T(t.tech)));add(T('{0}. Выбери, что будем рисовать.',T(t.tech)));add(T(t.tech)+'.');});
  VARS.forEach(v=>{add(T(v.name)+'.');[v.warm,...v.steps].forEach(s=>add(T(s.say)));});
  return[...o];
}
